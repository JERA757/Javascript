// Uso de los operadores de comparación en Javascript:
let valor1 = 5; 
let valor2 = 7; 

document.writeln(valor1 == valor2, '<br>');
document.writeln(valor1 != valor2, '<br>');
document.writeln(valor1 > valor2, '<br>');
document.writeln(valor1 < valor2, '<br>');
document.writeln(valor1 >= valor2, '<br>');
document.writeln(valor1 <= valor2, '<br>');
document.writeln(valor1 === valor2, '<br>');
document.writeln(valor1 !== valor2, '<br>');
