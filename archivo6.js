// Operadores lógicos: 
// AND (&&), OR (||), NOT (!)

let valor1 = true; 
let valor2 = false;

document.write('Usando el operador AND (&&): ' + (valor1 && valor2) + '<br>'); 
// false 

document.write('Usando el operador OR (||): ' + (valor1 || valor2) + '<br>'); 
// true

document.write('Usando el operador NOT (!): ' + (!valor1) + '<br>');
// false