// Operadores de asignación, incremento y decremento en Javascript:
let valor = 1; 

// Operador de pre-incremento:
++valor; // valor ahora es 2
document.write("Valor después del pre-incremento: " + valor + "<br>");

// Operador de post-incremento:
valor++; // valor ahora es 3
document.write("Valor después del post-incremento: " + valor + "<br>");

// Operador de pre-decremento:
--valor; // valor ahora es 2
document.write("Valor después del pre-decremento: " + valor + "<br>");

// Operador de post-decremento:
valor--; // valor ahora es 1
document.write("Valor después del post-decremento: " + valor + "<br>");

// Operadores de asignación:
valor += 1; // valor ahora es 2
document.write("Valor después de la asignación += 1: " + valor + "<br>");

valor -= 1; // valor ahora es 1
document.write("Valor después de la asignación -= 1: " + valor + "<br>");

valor *= 2; // valor ahora es 2
document.write("Valor después de la asignación *= 2: " + valor + "<br>");

valor /= 2; // valor ahora es 1
document.write("Valor después de la asignación /= 2: " + valor + "<br>");

valor %= 2; // valor ahora es 1
document.write("Valor después de la asignación %= 2: " + valor + "<br>");

valor **= 2; // valor ahora es 1
document.write("Valor después de la asignación **= 2: " + valor + "<br>");

